import { NextResponse } from "next/server";
import { loadOwner } from "@/lib/owner.mjs";
import { getDb } from "@/lib/db";
import { markdownToDocx } from "@/lib/mdToDocx";
import { briefChecks, briefChecksLine } from "@/lib/briefChecks";
import { localDateOf, localStamp } from "@/lib/dates.mjs";

export const dynamic = "force-dynamic";

export async function GET(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const brief = getDb()
    .prepare(
      `SELECT b.title, b.focus, b.content_md, b.status, b.created_at, b.checks, p.name AS person_name, c.name AS company_name
       FROM briefs b LEFT JOIN people p ON p.id = b.person_id LEFT JOIN companies c ON c.id = p.company_id WHERE b.id=?`
    )
    .get(Number(id)) as
    | {
        title: string;
        focus: string | null;
        content_md: string | null;
        status: string;
        created_at: string;
        checks: string | null;
        person_name: string | null;
        company_name: string | null;
      }
    | undefined;
  if (!brief || brief.status !== "ready" || !brief.content_md) {
    return NextResponse.json({ error: "brief not ready" }, { status: 404 });
  }

  const prepared = localStamp(brief.created_at);
  const checks = briefChecks(brief.checks);
  // The model's own first line is usually "# Prep: …" too; the title block replaces it.
  const body = brief.content_md.replace(/^\s*#\s+Prep:.*\n+/i, "");
  const buffer = await markdownToDocx(
    body,
    `Generated by ${loadOwner().appName} on ${prepared} — verify anything attributed to Gmail or the web before relying on it.`,
    {
      title: brief.person_name ? `Prep: ${brief.person_name}${brief.company_name ? ` — ${brief.company_name}` : ""}` : brief.title,
      lines: [
        `Prepared ${prepared}`,
        ...(brief.focus ? [`Focus: ${brief.focus}`] : []),
        ...(checks ? [briefChecksLine(checks)] : []),
      ],
    }
  );

  const safe = (brief.person_name ?? brief.title).replace(/[^\p{L}\p{N}\s-]/gu, "").trim().replace(/\s+/g, " ") || "brief";
  const filename = `Prep - ${safe} - ${localDateOf(brief.created_at)}.docx`;
  const asciiName = filename.replace(/[^\x20-\x7e]/g, "_").replace(/"/g, "");
  return new NextResponse(new Uint8Array(buffer), {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "Content-Disposition": `attachment; filename="${asciiName}"; filename*=UTF-8''${encodeURIComponent(filename)}`,
    },
  });
}

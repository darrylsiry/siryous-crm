describe("parseReport", () => {
  test("reads the run, version, severity sections, statuses, first seen and closed notes", () => {
    const r = parseReport("code", CODE);
    assert.equal(r.run, "2026-11-03 09:15");
    assert.equal(r.version, "abc12345");
    assert.ok(r.runAt);
    assert.equal(new Date(r.runAt!).getHours(), 9, "the agent's clock is this machine's clock");
    assert.match(r.headline, /Fix \*\*CR-002\*\* first/);
    assert.deepEqual(
      r.items.map((i) => [i.id, i.severity, i.status, i.statusText, i.firstSeen]),
      [
        ["CR-002", "High", "open", "New", null],
        ["CR-001", "Medium", "open", "Open", "2026-10-30"],
        ["CR-003", "Suggestion", "accepted", "Accepted", null],
      ]
    );
    assert.equal(r.items[0].title, "Stop losing the `last_touch` date");
    assert.deepEqual(r.closed, [{ id: "CR-000", title: "Old thing", status: "resolved", note: "resolved: the helper moved." }]);
  });

  test("ignores anything inside a fenced block", () => {
    assert.ok(!parseReport("code", CODE).items.some((i) => i.id === "CR-999"));
  });

  test("UX: first-seen and status from its table, paragraph findings, declined items", () => {
    const r = parseReport("ux", UX);
    const polish = r.items.find((i) => i.id === "UX-002")!;
    assert.equal(polish.severity, "P4 Polish");
    assert.equal(polish.firstSeen, "2026-11-03");
    assert.equal(polish.statusText, "New");
    assert.equal(polish.title, "Format dates one way");
    assert.equal(r.items.find((i) => i.id === "UX-001")!.statusText, "Improved");
    assert.deepEqual(r.closed.map((c) => [c.id, c.status]), [["UX-009", "declined"]]);
  });

  test("unrecognised or empty reports read as empty, never throw", () => {
    for (const text of ["", "hello", "## Summary", "| a | b |\n|---|---|"]) {
      const r = parseReport("security", text);
      assert.equal(r.run, null);
      assert.deepEqual(r.items, []);
    }
  });
});

describe("the ledger", () => {
  const run = (day: string, body: string) => parseReport("code", `- **Run:** ${day} 10:00\n\n## High\n\n${body}\n`);
  const fold = (l = emptyLedger(), ...runs: ReturnType<typeof run>[]) => {
    for (const r of runs) foldReport(l, r, r.runAt!);
    return l;
  };

  test("a finding a later run stops mentioning closes as no longer reported", () => {
    const l = fold(undefined, run("2026-11-01", "### CR-001 — A\n- **Status:** New"), run("2026-11-02", "None."));
    assert.equal(l.items["CR-001"].status, "resolved");
    assert.equal(l.items["CR-001"].statusText, "No longer reported");
    assert.equal(l.items["CR-001"].firstSeen, "2026-11-01");
    assert.equal(l.runs.length, 2);
  });

  test("a finding the reviewer resolves keeps its note, and comes back open if it returns", () => {
    const l = fold(
      undefined,
      run("2026-11-01", "### CR-001 — A\n- **Status:** New"),
      parseReport("code", "- **Run:** 2026-11-02 10:00\n\n## Resolved since last run\n- **CR-001 — A** — resolved: fixed the loop.\n")
    );
    assert.equal(l.items["CR-001"].statusText, "Resolved");
    assert.match(l.items["CR-001"].closedNote, /fixed the loop/);
    fold(l, run("2026-11-03", "### CR-001 — A\n- **Status:** Open (first seen 2026-11-01)"));
    assert.equal(l.items["CR-001"].status, "open");
    assert.equal(l.items["CR-001"].closedAt, null);
  });

  test("folding the same run twice changes nothing, and older runs never overwrite newer", () => {
    const first = run("2026-11-01", "### CR-001 — Old title\n- **Status:** New");
    const second = run("2026-11-02", "### CR-001 — New title\n- **Status:** Open");
    const l = fold(undefined, first, second);
    const once = JSON.stringify(l);
    fold(l, second, first);
    assert.equal(JSON.stringify(l), once);
    assert.equal(l.items["CR-001"].title, "New title");
  });

  test("one agent's run doesn't close another agent's findings", () => {
    const l = emptyLedger();
    const sec = parseReport("security", "- **Run:** 2026-11-01 10:00\n\n## High\n\n### SEC-001 — S\n- **Status:** New\n");
    foldReport(l, sec, sec.runAt!);
    const code = run("2026-11-02", "None.");
    foldReport(l, code, code.runAt!);
    assert.equal(l.items["SEC-001"].status, "open");
  });

  test("an unreadable ledger reads as empty", () => {
    assert.deepEqual(readLedger("not json").items, {});
    assert.deepEqual(readLedger(null).runs, []);
    assert.deepEqual(readLedger(JSON.stringify({ version: 99 })).items, {});
  });

  test("the page view: open sorted by severity, closed lists, set aside, totals", () => {
    const reports = { code: parseReport("code", CODE), ux: parseReport("ux", UX) };
    const v = activityView(emptyLedger(), reports);
    const code = v.agents.find((a) => a.info.key === "code")!;
    assert.deepEqual(code.open.map((i) => i.id), ["CR-002", "CR-001"]);
    assert.deepEqual(code.openBySeverity, [{ severity: "High", count: 1 }, { severity: "Medium", count: 1 }]);
    assert.deepEqual(code.setAside.map((i) => i.id), ["CR-003"]);
    assert.deepEqual(code.resolved.map((i) => i.id), ["CR-000"]);
    assert.equal(v.agents.find((a) => a.info.key === "security")!.report, null);
    assert.equal(v.totals.open, 4);
    assert.equal(v.totals.setAside, 2);
    assert.equal(v.totals.runs, 2);
  });
});

describe("reading reports from disk", () => {
  test("nothing there: no reports, an empty page, no badge", () => {
    assert.equal(hasReports(), false);
    assert.equal(urgentFindingCount(), 0);
    assert.equal(loadAgentActivity().view.totals.raised, 0);
    assert.equal(readReport("code"), null);
    assert.equal(mockupIds().size, 0);
  });

  test("with reports: found, counted, and absolute snapshot paths shortened", () => {
    const dir = reportsDir();
    fs.mkdirSync(path.join(dir, "code"), { recursive: true });
    fs.writeFileSync(path.join(dir, "code", "REPORT.md"), CODE + "\n/Users/someone/GitHub/crm/.review/code/lib/ai.ts:9\n");
    assert.equal(hasReports(), true);
    assert.equal(urgentFindingCount(), 1, "the High counts; the Medium doesn't");
    assert.ok(readReport("code")!.text.includes("\nlib/ai.ts:9"));
  });

  test("a mockup is read only by a strict ID", () => {
    const mockups = path.join(reportsDir(), "ux", "mockups");
    fs.mkdirSync(mockups, { recursive: true });
    fs.writeFileSync(path.join(mockups, "UX-001.html"), "<p>hi</p>");
    fs.writeFileSync(path.join(reportsDir(), "secret.html"), "nope");
    assert.equal(readMockup("UX-001"), "<p>hi</p>");
    assert.deepEqual([...mockupIds()], ["UX-001"]);
    for (const bad of ["../../secret", "UX-1", "CR-001", "UX-001.html", "UX-001/../../../secret"]) assert.equal(readMockup(bad), null, bad);
  });
});

describe("review-save.py", () => {
  const save = (key: string, text: string, reports: string) => {
    const out = path.join(tmp.dir, `out-${key}.txt`);
    fs.writeFileSync(out, text);
    return spawnSync("python3", ["scripts/review-save.py", key, out, reports], { encoding: "utf8" });
  };
  const python = spawnSync("python3", ["--version"]).status === 0;

  test("saves a report word for word, and refuses anything else", { skip: !python }, () => {
    const reports = path.join(tmp.dir, "save-a");
    assert.equal(save("code", CODE, reports).status, 0);
    assert.equal(fs.readFileSync(path.join(reports, "code", "REPORT.md"), "utf8"), CODE.trimEnd() + "\n");
    const bad = path.join(tmp.dir, "save-b");
    assert.notEqual(save("code", "I could not finish the review.", bad).status, 0);
    assert.notEqual(save("code", `Here is the report:\n${CODE}`, bad).status, 0);
    assert.ok(!fs.existsSync(path.join(bad, "code", "REPORT.md")));
  });

  test("UX: splits mockups into files and drops a resolved finding's mockup", { skip: !python }, () => {
    const reports = path.join(tmp.dir, "save-c");
    const ux = `# UX review: Siryous CRM\n\n## Mockup files\n\n\`\`\`html file=UX-001.html\n<p>before</p>\n\`\`\`\n`;
    assert.equal(save("ux", ux, reports).status, 0);
    const mockup = path.join(reports, "ux", "mockups", "UX-001.html");
    assert.equal(fs.readFileSync(mockup, "utf8"), "<p>before</p>\n");
    assert.match(fs.readFileSync(path.join(reports, "ux", "REPORT.md"), "utf8"), /^- UX-001\.html$/m);
    assert.equal(save("ux", `# UX review: Siryous CRM\n\n## Resolved since last run\n- **UX-001 — Keep it** — resolved: done.\n`, reports).status, 0);
    assert.ok(!fs.existsSync(mockup));
  });
});

describe("App Tests says when a report is behind the code", () => {
  const at = (iso: string) => new Date(iso);
  const now = Date.parse("2026-11-06T06:00:00Z");

  test("running, stuck, behind, current, or nothing to say", () => {
    assert.deepEqual(reviewStanding("8d0dee55", { runningSince: at("2026-11-06T05:40:00Z"), codeNow: "e6fd021e" }, now), {
      kind: "running",
      since: at("2026-11-06T05:40:00Z"),
    });
    assert.equal(reviewStanding("8d0dee55", { runningSince: at("2026-11-06T02:00:00Z"), codeNow: null }, now).kind, "stuck");
    assert.equal(reviewStanding("8d0dee55", { runningSince: null, codeNow: "e6fd021e" }, now).kind, "behind");
    assert.equal(reviewStanding("8d0dee55", { runningSince: null, codeNow: "8d0dee55" }, now).kind, "current");
    assert.equal(reviewStanding(null, { runningSince: null, codeNow: "8d0dee55" }, now).kind, "unknown");
    assert.equal(reviewStanding("8d0dee55", { runningSince: null, codeNow: null }, now).kind, "unknown");
  });

  test("the fingerprint comes from the runner, so it matches what the next run will review", async () => {
    const f = await reviewFreshness("code");
    const git = spawnSync("git", ["rev-parse", "--is-inside-work-tree"]).status === 0;
    if (git) assert.match(f.codeNow ?? "", /^[0-9a-f]{8}$/);
    const status = spawnSync("bash", ["scripts/review-run.sh", "code", "status"], { encoding: "utf8" }).stdout;
    if (git) assert.ok(status.includes(`code ${f.codeNow};`));
  });
});
